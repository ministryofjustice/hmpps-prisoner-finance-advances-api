CREATE TABLE revinfo (
                         rev BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         revtstmp TIMESTAMP WITH TIME ZONE NOT NULL
);

COMMENT ON TABLE revinfo IS 'Records all revisions';

COMMENT ON COLUMN revinfo.rev IS 'Primary key. An integer generated by the application. [Sensitivity: NONE]';
COMMENT ON COLUMN revinfo.revtstmp IS 'The timestamp for the audit log. [Sensitivity: NONE]';

CREATE TABLE advances_aud (
                           id UUID NOT NULL,
                           rev BIGINT NOT NULL,
                           revtype SMALLINT NOT NULL,
                           legacy_payment_profile_id BIGINT,
                           legacy_information_number VARCHAR(255),
                           prison_number             VARCHAR(255),
                           prison_id                 VARCHAR(255),
                           amount                    BIGINT,
                           created_on                TIMESTAMP WITH TIME ZONE,
                           repayment_start_date      TIMESTAMP WITH TIME ZONE,
                           repayment_amount          BIGINT,
                           reference                 VARCHAR(255),
                           created_by                VARCHAR(255),
                           status                    VARCHAR(255),
                           comment                   VARCHAR(255),
                           updated_at                TIMESTAMP WITH TIME ZONE,

                           CONSTRAINT pk_advances_aud
                                   PRIMARY KEY (id, rev),

                           CONSTRAINT fk_advances_aud_revision
                               FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

CREATE INDEX idx_advances_aud_rev ON advances_aud (rev);

COMMENT ON TABLE advances_aud IS 'A record of a change to an advance for audit purposes.';

COMMENT ON COLUMN advances_aud.id IS 'Primary key. A UUIDv7 generated by the application, used as the advances''s permanent public identifier across DPS. [Sensitivity: NONE]';
COMMENT ON COLUMN advances_aud.rev IS 'Revision of the change for advances entity. [Sensitivity: NONE]';
COMMENT ON COLUMN advances_aud.revtype IS 'Type of the revision of the change for advances entity. [Sensitivity: NONE]';
COMMENT ON COLUMN advances_aud.legacy_payment_profile_id IS 'NOMIS payment profile number, allowing these records to be linked back to the original source record held in NOMIS. [Sensitivity: NONE]';
COMMENT ON COLUMN advances_aud.legacy_information_number IS 'NOMIS advance information number, allowing these records to be linked back to the original source record held in NOMIS. [Sensitivity: NONE]';
COMMENT ON COLUMN advances_aud.prison_number IS 'NOMIS offender number (prison number/noms number) of the prisoner that the money has been advanced to. The link that makes every row here personal data about that prisoner. Updated in place when NOMIS merges two offender records. [Sensitivity: PERSONAL]';
COMMENT ON COLUMN advances_aud.prison_id IS 'Prison code, such as MDI, where the money advanced to the prisoner was from. Read with prison_number it indicates where that prisoner was held at the time. [Sensitivity: PERSONAL]';
COMMENT ON COLUMN advances_aud.amount IS 'The amount of money that is/was advanced to the prisoner. [Sensitivity: OFFICIAL-SENSITIVE]';
COMMENT ON COLUMN advances_aud.repayment_start_date IS 'When the repayments did/will start to be taken from the prisoner. [Sensitivity: NONE]';
COMMENT ON COLUMN advances_aud.repayment_amount IS 'The amount of money that will be attempted to be taken as a repayment towards the advance of monies to the prisoner. [Sensitivity: OFFICIAL-SENSITIVE]';
COMMENT ON COLUMN advances_aud.reference IS 'Free text reference value about the advance. Free text: assume it can name an incident, prisoner, staff member or member of the public, for example when accidentally used instead of the comment explaining why the money has been advanced or who has approved the advance. [Sensitivity: NONE]';
COMMENT ON COLUMN advances_aud.created_on IS 'When this advance record was first created, indicating when the prisoner received the advance of money which combined with the amount could implicate the prisoner as a target for coercion. [Sensitivity: OFFICIAL-SENSITIVE]';
COMMENT ON COLUMN advances_aud.created_by IS 'DPS username of the person who recorded the advance to the prisoner from the prison. [Sensitivity: STAFF]';
COMMENT ON COLUMN advances_aud.updated_at IS 'When this advance record was last updated. [Sensitivity: NONE]';
COMMENT ON COLUMN advances_aud.status IS 'The current status of this advance - ACTIVE, REPAID, WRITTEN_OFF. [Sensitivity: NONE]';
COMMENT ON COLUMN advances_aud.comment IS 'Free text description about the advance. Free text: assume it can name an incident, prisoner, staff member or member of the public, for example when explaining why the money has been advanced or who has approved the advance. [Sensitivity: OFFICIAL-SENSITIVE]';
