CREATE TABLE advance_write_off
(
    id                       UUID                        NOT NULL,

    advance_record_id        UUID                        NOT NULL,

    amount                   INTEGER                     NOT NULL,

    created_at               TIMESTAMP WITH TIME ZONE    NOT NULL,

    created_by               VARCHAR(255)                NOT NULL,

    CONSTRAINT pk_advance_write_off PRIMARY KEY (id),
    CONSTRAINT fk_advance_write_off_advance_record FOREIGN KEY (advance_record_id) REFERENCES advance_records(id)
);

COMMENT ON TABLE advance_write_off IS 'A record of a write-off for a prisoner advance';

COMMENT ON COLUMN advance_write_off.id IS 'Primary key. A UUIDv7 generated by the application, used as the advance payment''s permanent public identifier across DPS. [Sensitivity: NONE]';
COMMENT ON COLUMN advance_write_off.advance_record_id IS 'Foreign key. A UUIDv7 generated by the application, used as the advance record id''s permanent public identifier across DPS. [Sensitivity: NONE]';
COMMENT ON COLUMN advance_write_off.amount IS 'The amount of money that was written-off to the prisoner. [Sensitivity: OFFICIAL-SENSITIVE]';
COMMENT ON COLUMN advance_write_off.created_by IS 'DPS username of the person who wrote off the advance of the prisoner. [Sensitivity: STAFF]';
COMMENT ON COLUMN advance_write_off.created_at IS 'When this advance write-off was first created. [Sensitivity: NONE]';