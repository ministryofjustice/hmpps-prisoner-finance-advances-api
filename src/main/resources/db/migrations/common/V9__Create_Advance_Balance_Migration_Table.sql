CREATE TABLE advance_balance_migrations
(
    advance_balance_migration_id UUID                        NOT NULL,

    advance_record_id            UUID                        NOT NULL,

    amount_outstanding           INTEGER                     NOT NULL,

    timestamp                    TIMESTAMP WITH TIME ZONE    NOT NULL,

    CONSTRAINT pk_advance_balance_migrations PRIMARY KEY (advance_balance_migration_id),
    CONSTRAINT fk_advance_balance_migrations_advance_record FOREIGN KEY (advance_record_id) REFERENCES advance_records(id)
);

COMMENT ON TABLE advance_balance_migrations IS 'A record of a write-off for a prisoner advance';
COMMENT ON COLUMN advance_balance_migrations.advance_balance_migration_id IS 'Primary key. A UUIDv7 generated by the application, used as the advance migrations'' permanent public identifier across DPS. [Sensitivity: NONE]';
COMMENT ON COLUMN advance_balance_migrations.advance_record_id IS 'Foreign key. A UUIDv7 generated by the application, used as the advance record id''s permanent public identifier across DPS. [Sensitivity: NONE]';
COMMENT ON COLUMN advance_balance_migrations.amount_outstanding IS 'The amount of money in pence that was outstanding on the advance at the time of the migration. [Sensitivity: OFFICIAL-SENSITIVE]';
COMMENT ON COLUMN advance_balance_migrations.timestamp IS 'The time the migration was applied [Sensitivity: NONE]';